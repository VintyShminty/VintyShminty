const SLUG_KEYS = Object.keys(BY_SLUG).sort((a, b) => b.length - a.length);

/**
 * The icon of a category: by its slug when it is listed above (the longest matching end of the slug), else by the
 * icon name from the category table (a row's own, or the nearest one above it), else a tag.
 */
export function categoryIcon(name: string | null | undefined, slug?: string): LucideIcon {
  if (slug) {
    const key = SLUG_KEYS.find((k) => slug === k || slug.endsWith(`-${k}`));
    if (key) return BY_SLUG[key] as LucideIcon;
  }
  return (name && BY_NAME[name]) || Tag;
}
